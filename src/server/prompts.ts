/** 빠른 선생님 모드 공통 프롬프트를 신중한 선생님 모드로 바꾼다(그림 주문 대신 직접 그리기). 바꿀 문장이 없으면 던진다(테스트가 잡는다). */
function toDeep(common: string): string {
  const swap = (from: string, to: string) => {
    if (!common.includes(from)) throw new Error(`deep prompt: 바꿀 문장을 못 찾음: ${from.slice(0, 40)}`);
    common = common.replace(from, to);
  };
  swap('그림은 솜씨 좋은 화가가 네 주문을 받아 따로 그려 줘.',
    '그림도 네가 직접 마커 선(좌표)으로 그려. 쓰기 전에 짧게 생각해서 수업의 뼈대만 정해: 한 문장 답, 비유 하나, 2~3단계, 단계마다 어떤 설명 그림(무엇을 나란히, 화살표는 어디서 어디로)을 그릴지. 좌표는 미리 계산하지 말고 그 그림 줄을 쓸 때 정해. 듣는 사람이 기다리고 있으니 뼈대가 서면 바로 쓰기 시작해.');
  swap('- 줄은 다섯 가지뿐이야.', '- 줄은 네 가지뿐이야(그림 주문 sketch 줄은 쓰지 마).');
  swap('  2. {"sketch":{"id":"병사","size":"small","describe":"장면 묘사"}} — 화가에게 그림 주문. 보드에는 아직 안 나타나.\n', '');
  const a = common.indexOf('# 그림 주문(sketch)과 보여 주기');
  const b = common.indexOf('# 판서 ("draw" 안에 넣는 것)');
  if (a < 0 || b < 0) throw new Error('deep prompt: 그림 주문 절을 못 찾음');
  common = common.slice(0, a) + `# 그림 직접 그리기(figure)
- 설명 그림은 {"draw":{"kind":"figure","id":"거리","size":"wide","ink":"black","strokes":[...],"labels":[...]},"at":"낱말"}로, 그 그림을 말하는 say 바로 뒤에 써. 그 낱말을 말하는 순간 그려져.
- 한 수업에 그림 3~6개. 설명의 단계마다 그림 하나씩 그려서, 그림 없이 say가 세 문장 넘게 이어지지 않게 해. 그림 하나에 생각 하나. 칸이 차면 {"page":true}로 넘기고 계속 그려. "id"는 짧은 이름, 수업 안에서 겹치지 않게.
- 이름표(labels)는 그림 선과 다른 이름표에서 떨어진 빈 곳에 둬. 가리키는 대상이 멀면 짧은 선(화살표 아님)으로 이어 줘.
- 신중한 선생님은 더 깊이 가르쳐: say는 18~26문장까지 써도 되고(문장 길이는 듣는 사람 기준 그대로), 그만큼 원리·단계·예를 더 담아. 늘어난 문장을 상투어로 채우지 마.
- "size": "small"은 정사각형 칸 하나(가로·세로 0~100), "wide"는 한 줄 전체를 쓰는 넓은 칸(가로 0~100, 세로 0~37).
- 아래는 그림을 선으로 그리는 규칙이야. 여기서 "주문"은 네가 설계한 그림 계획이야.

${DRAWING_RULES}
# 좋은 그림 예시(각 JSON이 figure 하나 — "draw" 안에 그대로 넣으면 돼)
${drawingExamples()}

` + common.slice(b);
  swap('- sketch — 주문한 그림 보여 주기(위 참고).\n', '');
  swap('- figure — 직접 그리는 선 그림. 화살표·네모처럼 아주 단순한 도형일 때만 쓰고, 나머지는 sketch로 주문해.', '- figure — 설명 그림(위 "그림 직접 그리기" 규칙대로).');
  swap(' 그 바로 뒤에 sketch 주문들이 와.', '');
  return common;
}

