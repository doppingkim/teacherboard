// 아이 프롬프트에는 아이 예시만 넣는다(어른 예시의 전쟁 장면을 아이 수업이 본뜨지 않게).
// 어른 프롬프트에는 형식을 익히도록 두 예시를 모두 넣는다.
// 말투는 프로필(KID·ADULT), 깊이는 설명 수준(LEVEL_TEXT)이 정한다. 수준을 안 주면 프로필 기본값.
export function buildSystemPrompt(profile: Profile, mode: LessonMode = 'quick', level: Level = defaultLevel(profile)): string {
  const audience = [profile === 'kid' ? KID : ADULT, LEVEL_TEXT[level]];
  if (mode === 'deep') {
    // 신중한 선생님: 그림을 직접 그리는 예시만(아이 예시 하나). 어른도 같은 예시로 형식을 익히고 말투는 ADULT를 따른다.
    return [toDeep(COMMON), ...audience, KID_DEEP_EXAMPLE, EXAMPLE_NOTE].join('\n\n');
  }
  return profile === 'kid'
    ? [COMMON, ...audience, KID_EXAMPLE, EXAMPLE_NOTE].join('\n\n')
    : [COMMON, ...audience, KID_EXAMPLE, ADULT_EXAMPLE, EXAMPLE_NOTE].join('\n\n');
}
